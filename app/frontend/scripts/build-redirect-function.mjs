// Generates infra/cloudfront-url-tidy.js — the CloudFront Function (viewer
// request) that 301-redirects the two URL shapes that otherwise answer with the
// wrong thing:
//
//   /cbse-online-tuition.html  ->  /cbse-online-tuition
//   /faq/                      ->  /faq
//
// Neither has an S3 key, so today both fall through CloudFront's error handling
// and serve the homepage with a 200 — a duplicate of a real page under a URL
// that should not exist. A 301 to the clean URL is what a crawler needs.
//
// The route list is generated from the same data the prerender uses, so a new
// route can never be left out of it. Only paths in that list are redirected,
// which is what keeps the real .html pages (/about.html, /terms.html, the blog
// posts) untouched: stripping ".html" from those gives a path that is not a
// route, so the function leaves the request alone.
//
// Run by `npm run build`. Output is committed so the deployed function can be
// diffed against the repo.

import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { ALL_TUITION_PAGES } from '../src/data/tuitionLandingPages.js';
import { STATIC_ROUTE_HEADS } from '../src/data/staticRouteHeads.js';
import { PRACTICE_WORKSHEET_ROUTES } from '../src/data/practiceWorksheetRoutes.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const outFile = path.join(root, 'infra', 'cloudfront-url-tidy.js');

const routes = [
  ...Object.keys(STATIC_ROUTE_HEADS),
  ...ALL_TUITION_PAGES.map((p) => `/${p.slug}`),
  ...PRACTICE_WORKSHEET_ROUTES.map((w) => `/${w.slug}`),
  '/admin',
]
  .filter((r) => r !== '/')
  .sort();

const unique = [...new Set(routes)];
if (unique.length !== routes.length) throw new Error('build-redirect-function: duplicate route in the list');
for (const r of unique) {
  if (!/^\/[a-z0-9-]+$/.test(r)) throw new Error(`build-redirect-function: unexpected route shape ${r}`);
}

// One object literal, which is how a CloudFront Function does a set lookup.
const table = unique.map((r) => `  '${r}': 1,`).join('\n');

const code = `// GENERATED by app/frontend/scripts/build-redirect-function.mjs — do not edit.
//
// CloudFront Function, viewer request, runtime cloudfront-js-2.0.
// Sends the ".html" twin and the trailing-slash form of a real route to the
// route itself with a 301, instead of letting them fall through to the SPA
// fallback and answer 200 with homepage markup.
//
// Every other request — real files, the genuine .html pages, assets, /admin —
// is returned untouched.

var ROUTES = {
${table}
};

function redirect(to) {
  return {
    statusCode: 301,
    statusDescription: 'Moved Permanently',
    headers: {
      location: { value: to },
      'cache-control': { value: 'max-age=3600' },
    },
  };
}

function handler(event) {
  var request = event.request;
  var uri = request.uri;
  var target = null;

  if (uri.length > 5 && uri.substr(uri.length - 5) === '.html') {
    var stripped = uri.substr(0, uri.length - 5);
    if (ROUTES[stripped] === 1) target = stripped;
  } else if (uri.length > 1 && uri.substr(uri.length - 1) === '/') {
    var trimmed = uri.substr(0, uri.length - 1);
    if (ROUTES[trimmed] === 1) target = trimmed;
  }

  if (target === null) return request;

  // Keep any query string, so ?utm_source=... survives the redirect.
  var qs = request.querystring;
  var parts = [];
  for (var key in qs) {
    var v = qs[key];
    if (v.multiValue) {
      for (var i = 0; i < v.multiValue.length; i++) {
        parts.push(v.multiValue[i].value === '' ? key : key + '=' + v.multiValue[i].value);
      }
    } else {
      parts.push(v.value === '' ? key : key + '=' + v.value);
    }
  }

  return redirect(parts.length > 0 ? target + '?' + parts.join('&') : target);
}
`;

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, code);

const bytes = Buffer.byteLength(code, 'utf8');
// CloudFront Functions are limited to 10 KB of source.
if (bytes > 10 * 1024) throw new Error(`build-redirect-function: ${bytes} bytes exceeds the 10 KB function limit`);
console.log(`cloudfront-url-tidy.js: ${unique.length} routes, ${bytes} bytes`);
